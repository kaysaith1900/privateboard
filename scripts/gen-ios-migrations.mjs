#!/usr/bin/env node
/**
 * gen-ios-migrations.mjs · codegen the iOS data-layer migration registry.
 *
 * Reads every `src/storage/migrations/NNN_*.sql` (the SAME files the Node
 * server runs via src/storage/db.ts) and emits a Swift source file listing
 * them, in order, as (name, sql) pairs. The on-device GRDB `DatabaseMigrator`
 * registers these verbatim so the phone's schema is byte-identical to the
 * desktop's — see ~/.claude/plans/privateboard-iterative-church.md.
 *
 * Run from the repo root:  node scripts/gen-ios-migrations.mjs
 * Re-run whenever a migration is added under src/storage/migrations/.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const migDir = join(repoRoot, "src/storage/migrations");
const outFile = join(
  repoRoot,
  "ios/BoardroomKit/Sources/BoardroomStorage/Migrations.generated.swift",
);

const files = readdirSync(migDir)
  .filter((f) => f.endsWith(".sql"))
  .sort(); // 001_… < 002_… — lexical sort matches numeric order (zero-padded)

if (files.length === 0) {
  console.error(`[gen-ios-migrations] no .sql files in ${migDir}`);
  process.exit(1);
}

/** Pick a Swift raw-string pound fence wide enough that `sql` can't close it
 *  early. A raw literal `#"""…"""#` ends at `"""` followed by N `#`s; bump N
 *  until the content contains no such closing run. */
function fence(sql) {
  let n = 1;
  while (sql.includes(`"""${"#".repeat(n)}`)) n++;
  return "#".repeat(n);
}

const entries = files
  .map((name) => {
    const sql = readFileSync(join(migDir, name), "utf8");
    const f = fence(sql);
    return `    (name: "${name}", sql: ${f}"""\n${sql}\n"""${f}),`;
  })
  .join("\n");

const swift = `// Generated by scripts/gen-ios-migrations.mjs — DO NOT EDIT BY HAND.
// Source of truth: src/storage/migrations/*.sql (${files.length} migrations).
// Re-run \`node scripts/gen-ios-migrations.mjs\` after adding a migration.

import Foundation

public enum SchemaMigrations {
    /// Every migration in declaration order. Each \`sql\` is the verbatim
    /// contents of the corresponding \`src/storage/migrations/NNN_*.sql\` file;
    /// \`name\` is the file name, used as the GRDB migration identifier so the
    /// applied-set is stable and matches the desktop \`_migrations\` keys.
    public static let all: [(name: String, sql: String)] = [
${entries}
    ]
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, swift, "utf8");
console.log(`[gen-ios-migrations] wrote ${files.length} migrations → ${outFile}`);
