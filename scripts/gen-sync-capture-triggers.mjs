// Generate migration 060 · sync capture triggers. Each syncable table gets
// AFTER INSERT/UPDATE/DELETE triggers that stage a row into sync_outbox (hlc
// filled at flush by src/sync/capture.ts). Capture only when sync is ENABLED
// (sync_state.enabled='1') and not suppressed during a merge (cap_off<>'1') —
// so it's a no-op / zero behavior change while sync is off. cols_json =
// json_object of the SYNCED columns (device-local / unique-counter cols excluded).
// Re-run: `node scripts/gen-sync-capture-triggers.mjs` then gen-ios-migrations.mjs.
import { writeFileSync } from "node:fs";

const SPEC = {
  rooms: { mode: "lww", cols: ["name","subject","mode","status","brief_style","created_at","intensity","parent_room_id","parent_brief_id","delivery_mode","vote_trigger","room_kind","thread_director_id"] },
  agents: { mode: "lww", cols: ["name","handle","role_tag","bio","cover_quote","instruction","model_v","avatar_path","created_at","updated_at","role_kind","ability_json","web_search_enabled","carrier_pref","voice_json","persona_spec_json","model_by_provider_json","voice_by_provider_json","user_rules_json","avatar3d_json"] },
  key_points: { mode: "lww", cols: ["room_id","message_id","round_num","body","vote","position","created_at","voted_at"] },
  notes: { mode: "lww", cols: ["room_id","message_id","author_kind","author_id","author_name","quote_text","context_before","context_after","char_offset_start","char_offset_end","user_note","tags_json","status","created_at"] },
  messages: { mode: "append", cols: ["room_id","author_kind","author_id","reply_to_id","body","meta_json","round_num","created_at"] },
  briefs: { mode: "append", cols: ["room_id","style","title","body_md","body_json","supplement","spine","components_json","composer_rationale","subject_type","house_style","assets_json","created_at","mode","viewer_variant"] },
  user_long_memory: { mode: "append", cols: ["label","claim","confidence","provenance_rooms","last_reinforced_at","superseded_by","created_at","updated_at"] },
  agent_memories: { mode: "append", cols: ["agent_id","content","kind","source","source_room","confidence","pinned","created_at","updated_at","tier","usage_count","last_used_at","superseded_by","consolidated_from","provenance_rooms"] },
};

const MS = "CAST((julianday('now')-2440587.5)*86400000 AS INTEGER)";
const GUARD = "(SELECT value FROM sync_state WHERE key='enabled')='1' AND COALESCE((SELECT value FROM sync_state WHERE key='cap_off'),'0') <> '1'";
const OPID = "lower(hex(randomblob(16)))";

const jsonObj = (cols, ref) => "json_object(" + cols.map((c) => `'${c}', ${ref}.${c}`).join(", ") + ")";
const stage = (entity, pkExpr, op, colsExpr) =>
  `  INSERT INTO sync_outbox (op_id, entity, pk, op, cols_json, hlc, created_at)\n  VALUES (${OPID}, '${entity}', ${pkExpr}, '${op}', ${colsExpr}, '', ${MS});`;

// Build the CREATE block + the matching DROP block from the SPEC. 060 ships the
// CREATEs (fresh installs); 061 ships DROP+CREATE so devices that already ran the
// v1 triggers pick up column changes (e.g. rooms.status added in v2). Same SPEC
// → the two can never drift.
let creates = "";
let drops = "";
for (const [t, { mode, cols }] of Object.entries(SPEC)) {
  creates += `-- ${t} (${mode})\n`;
  creates += `CREATE TRIGGER IF NOT EXISTS sync_cap_${t}_ins AFTER INSERT ON ${t}\nWHEN ${GUARD}\nBEGIN\n${stage(t, "NEW.id", "upsert", jsonObj(cols, "NEW"))}\nEND;\n`;
  drops += `DROP TRIGGER IF EXISTS sync_cap_${t}_ins;\n`;
  if (mode === "lww") {
    creates += `CREATE TRIGGER IF NOT EXISTS sync_cap_${t}_upd AFTER UPDATE ON ${t}\nWHEN ${GUARD}\nBEGIN\n${stage(t, "NEW.id", "upsert", jsonObj(cols, "NEW"))}\nEND;\n`;
    drops += `DROP TRIGGER IF EXISTS sync_cap_${t}_upd;\n`;
  }
  creates += `CREATE TRIGGER IF NOT EXISTS sync_cap_${t}_del AFTER DELETE ON ${t}\nWHEN ${GUARD}\nBEGIN\n${stage(t, "OLD.id", "delete", "NULL")}\nEND;\n\n`;
  drops += `DROP TRIGGER IF EXISTS sync_cap_${t}_del;\n`;
}

const head060 = `-- iCloud sync · capture triggers (generated by scripts gen060 · see migration design).
-- Stage every write to a syncable table into sync_outbox; the flush step assigns
-- the HLC + per-field clock. Echo-suppressed: applyOps sets sync_state 'cap_off'='1'
-- around its writes so merges never re-capture. room_members is intentionally
-- absent (composite PK · handled in a later migration). PURELY ADDITIVE.\n\n`;
writeFileSync(
  new URL("../src/storage/migrations/060_sync_capture_triggers.sql", import.meta.url),
  head060 + creates,
);

const head061 = `-- iCloud sync · REBUILD capture triggers (generated). Drops every sync_cap_*
-- trigger and recreates it from the current column SPEC, so devices that already
-- ran migration 060 (v1 columns) pick up later additions — v2 adds rooms.status
-- to the synced set. Idempotent (DROP IF EXISTS + CREATE IF NOT EXISTS).\n\n`;
writeFileSync(
  new URL("../src/storage/migrations/061_sync_capture_triggers_v2.sql", import.meta.url),
  head061 + drops + "\n" + creates,
);
console.log("wrote migrations 060 + 061 ·", Object.keys(SPEC).length, "tables");

// ── Genesis · one-time full export of existing rows ──────────────────────────
// The capture triggers only fire on writes AFTER sync is enabled, so a device
// that already has directors / rooms / memories needs a one-shot dump of every
// existing row into sync_outbox the first time it syncs to a given folder. We
// generate it from the SAME column SPEC (single source of truth) so it can never
// drift from the triggers, and emit it for BOTH platforms. Reuses the exact
// json_object() column set → an upsert carrying the full synced row. Idempotent
// per-folder via a `genesis:<folder>` marker in sync_state (engine side).
const genesisStmts = Object.entries(SPEC).map(([t, { cols }]) =>
  `INSERT INTO sync_outbox (op_id, entity, pk, op, cols_json, hlc, created_at) ` +
  `SELECT ${OPID}, '${t}', ${t}.id, 'upsert', ${jsonObj(cols, t)}, '', ${MS} FROM ${t}`,
);

// Bump when the synced column set or blob handling changes, so every device
// re-exports once (the marker key is `genesis:<folder>:v<VERSION>`) and peers
// re-apply with the fix. v2 = rooms.status added + iOS blob download-wait fix.
const GENESIS_VERSION = 2;

// TS consumer · src/sync/genesis.generated.ts
const tsBody =
  `// AUTO-GENERATED by scripts/gen-sync-capture-triggers.mjs · do not edit by hand.\n` +
  `// One INSERT…SELECT per syncable table · stages every existing row into\n` +
  `// sync_outbox (hlc='' → filled by flushStaged at push time). See SyncEngine.ensureGenesis.\n\n` +
  `export const GENESIS_VERSION = ${GENESIS_VERSION};\n\n` +
  `export const GENESIS_STATEMENTS: readonly string[] = [\n` +
  genesisStmts.map((s) => `  ${JSON.stringify(s)},`).join("\n") +
  `\n];\n`;
writeFileSync(new URL("../src/sync/genesis.generated.ts", import.meta.url), tsBody);

// Swift consumer · ios/BoardroomKit/Sources/BoardroomSync/Genesis.generated.swift
const swiftBody =
  `// AUTO-GENERATED by scripts/gen-sync-capture-triggers.mjs · do not edit by hand.\n` +
  `// Mirror of src/sync/genesis.generated.ts — full-row export per syncable table.\n\n` +
  `public enum SyncGenesis {\n` +
  `    public static let version = ${GENESIS_VERSION}\n` +
  `    public static let statements: [String] = [\n` +
  genesisStmts.map((s) => `        ${JSON.stringify(s)},`).join("\n") +
  `\n    ]\n}\n`;
writeFileSync(
  new URL("../ios/BoardroomKit/Sources/BoardroomSync/Genesis.generated.swift", import.meta.url),
  swiftBody,
);
console.log("wrote genesis · TS + Swift ·", genesisStmts.length, "tables");
